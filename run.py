#!/usr/bin/env python3
"""Start or reuse the local Claude container and launch an interactive session."""

from __future__ import annotations

import argparse
import json
import os
import posixpath
import pwd
import grp
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path



PROJECT_DIR = Path(__file__).resolve().parent
COMPOSE_FILE = PROJECT_DIR / "docker-compose.yml"
ENV_FILE = PROJECT_DIR / ".env"
ENV_EXAMPLE_FILE = PROJECT_DIR / ".env.example"
OVERRIDE_FILE = PROJECT_DIR / "docker-compose.override.yml"
OVERRIDE_MARKER = "# Generated by run.py"
EXTRA_VOLUMES_VAR = "EXTRA_VOLUMES"
WORKSPACE_ROOT = "/workspace"


@dataclass(frozen=True)
class Mount:
	"""A host directory shared with the container."""

	host: Path
	target: str
	mode: str  # "rw" or "ro"


@dataclass(frozen=True)
class ContainerInfo:
	"""Facts about the running container, read from Docker rather than assumed."""

	username: str
	uid: str
	gid: str
	home: str
	mounts: list[Mount]  # extra bind mounts, excluding the home mount


def parse_args() -> argparse.Namespace:
	"""Parse command line arguments for interactive session mode."""
	parser = argparse.ArgumentParser(
		description="Start or reuse the local Claude container and open a shell session."
	)
	parser.add_argument(
		"--root",
		action="store_true",
		help="Open an interactive root shell instead of launching claude.",
	)
	parser.add_argument(
		"--recreate",
		action="store_true",
		help="Recreate the container to apply changed volumes or UID/GID (ends other open sessions).",
	)
	return parser.parse_args()


def ensure_env_file_exists() -> bool:
	"""Ensure .env exists, creating it from .env.example on first run. Returns True if created."""
	if ENV_FILE.exists():
		return False

	if not ENV_EXAMPLE_FILE.exists():
		fail(f"Missing {ENV_FILE} and template {ENV_EXAMPLE_FILE}.")

	try:
		shutil.copy2(ENV_EXAMPLE_FILE, ENV_FILE)
		ENV_EXAMPLE_FILE.unlink()
	except OSError as error:
		fail(f"Could not initialize {ENV_FILE.name} from {ENV_EXAMPLE_FILE.name}: {error}")
	return True


def _owner_mode(path: Path) -> str:
	stat = path.stat()
	try:
		owner = pwd.getpwuid(stat.st_uid).pw_name
	except KeyError:
		owner = str(stat.st_uid)
	try:
		group = grp.getgrgid(stat.st_gid).gr_name
	except KeyError:
		group = str(stat.st_gid)
	mode = oct(stat.st_mode & 0o777)
	return f"{owner}:{group} {mode}"


def fail(message: str, code: int = 1) -> None:
	print(f"❌ {message}")
	sys.exit(code)


def run(cmd: list[str], *, check: bool = True, capture: bool = True) -> subprocess.CompletedProcess[str]:
	return subprocess.run(
		cmd,
		cwd=PROJECT_DIR,
		check=check,
		text=True,
		capture_output=capture,
	)


def get_service_name() -> str:
	result = run(["docker", "compose", "config", "--services"], check=False, capture=True)
	if result.returncode != 0:
		fail("Could not resolve service name from docker-compose.yml.")

	services = [line.strip() for line in result.stdout.splitlines() if line.strip()]
	if not services:
		fail("No services found in docker-compose.yml.")

	return services[0]


def _container_ref() -> str | None:
	"""Return the running container ID for the compose service, or None."""
	service_name = get_service_name()
	container_id = run(["docker", "compose", "ps", "-q", service_name], check=False, capture=True)
	if container_id.returncode != 0 or not container_id.stdout.strip():
		return None
	return container_id.stdout.strip().splitlines()[0]


def is_container_running() -> bool:
	container_ref = _container_ref()
	if container_ref is None:
		return False

	result = run(
		["docker", "inspect", "-f", "{{.State.Running}}", container_ref],
		check=False,
		capture=True,
	)
	if result.returncode != 0:
		return False
	return result.stdout.strip().lower() == "true"


def ensure_runtime_prereqs() -> None:
	if shutil.which("docker") is None:
		fail("Docker is not installed or not available in PATH.")

	compose_ok = subprocess.run(
		["docker", "compose", "version"],
		cwd=PROJECT_DIR,
		check=False,
		text=True,
		stdout=subprocess.DEVNULL,
		stderr=subprocess.DEVNULL,
	).returncode == 0

	if not compose_ok:
		fail("Docker Compose plugin is not available. Install Docker Compose v2.")


def ensure_writable_directory(path: Path, label: str) -> None:
	try:
		path.mkdir(parents=True, exist_ok=True)
	except PermissionError:
		fail(f"Cannot create {label} at {path}. Check directory ownership/permissions.")

	if not os.access(path, os.R_OK | os.W_OK | os.X_OK):
		fail(
			f"{label} is not writable by current user ({path}, owner {_owner_mode(path)}). "
			"Fix permissions before starting the container."
		)


def _load_dotenv() -> dict[str, str]:
	env_data: dict[str, str] = {}
	ensure_env_file_exists()
	if not ENV_FILE.exists():
		return env_data

	for raw_line in ENV_FILE.read_text(encoding="utf-8").splitlines():
		line = raw_line.strip()
		if not line or line.startswith("#") or "=" not in line:
			continue
		name, value = line.split("=", 1)
		env_data[name.strip()] = value.strip().strip('"').strip("'")
	return env_data


def _get_setting(name: str, env_data: dict[str, str], default: str = "") -> str:
	"""Resolve a setting from the process environment, then .env, then a default."""
	return os.environ.get(name) or env_data.get(name) or default


def _expand_compose_var(text: str, env_data: dict[str, str]) -> str:
	"""Expand ${VAR} and ${VAR:-default} syntax used in docker-compose files."""

	def replace(match: re.Match[str]) -> str:
		var_name = match.group(1)
		default_value = match.group(2)
		if var_name in os.environ and os.environ[var_name] != "":
			return os.environ[var_name]
		if var_name in env_data and env_data[var_name] != "":
			return env_data[var_name]
		return default_value or ""

	pattern = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)(?::-([^}]*))?\}")
	return pattern.sub(replace, text)


def _get_container_home(env_data: dict[str, str]) -> str:
	"""Resolve container HOME path from docker-compose.yml environment section."""
	for raw_line in COMPOSE_FILE.read_text(encoding="utf-8").splitlines():
		line = raw_line.strip()
		if not line.startswith("- HOME="):
			continue
		home_value = line[len("- HOME=") :].strip()
		home_value = _expand_compose_var(home_value, env_data)
		if home_value:
			return home_value

	return "/home/claude"


def _parse_compose_mounts() -> dict[str, Path]:
	"""Return host paths for key container mount targets from docker-compose.yml."""
	if not COMPOSE_FILE.exists():
		fail(f"Missing compose file: {COMPOSE_FILE}")
	env_data = _load_dotenv()
	container_home = _get_container_home(env_data)

	mount_targets = {
		container_home: "Claude home mount",
	}

	found: dict[str, Path] = {}
	for raw_line in COMPOSE_FILE.read_text(encoding="utf-8").splitlines():
		line = raw_line.strip()
		if not line.startswith("- "):
			continue

		entry = line[2:].split(" #", 1)[0].strip()
		if ":" not in entry:
			continue

		parts = entry.split(":")
		if len(parts) < 2:
			continue

		host_raw = _expand_compose_var(parts[0].strip(), env_data)
		target = _expand_compose_var(parts[1].strip(), env_data)
		if target not in mount_targets:
			continue

		# Only validate bind mounts with filesystem paths.
		if not (host_raw.startswith("/") or host_raw.startswith("~") or host_raw.startswith(".")):
			continue

		host_path = Path(host_raw).expanduser()
		if host_raw.startswith("."):
			host_path = (PROJECT_DIR / host_raw).resolve()

		found[mount_targets[target]] = host_path

	return found


def preflight_checks() -> None:
	compose_check = subprocess.run(
		["docker", "compose", "config"],
		cwd=PROJECT_DIR,
		check=False,
		text=True,
		stdout=subprocess.DEVNULL,
		stderr=subprocess.PIPE,
	)
	if compose_check.returncode != 0:
		error = compose_check.stderr.strip() or "Unknown docker compose configuration error."
		fail(f"docker-compose.yml validation failed: {error}")

	mounts = _parse_compose_mounts()
	if not mounts:
		fail("Could not detect Claude bind mounts in docker-compose.yml volumes.")

	for label, host_path in mounts.items():
		ensure_writable_directory(host_path, label)


def parse_extra_volumes(env_data: dict[str, str], container_home: str) -> list[Mount]:
	"""Parse EXTRA_VOLUMES (comma-separated host[:container][:ro|rw]) into mounts."""
	mounts: list[Mount] = []
	used_targets: set[str] = set()

	for entry in _get_setting(EXTRA_VOLUMES_VAR, env_data).split(","):
		entry = entry.strip()
		if not entry:
			continue

		parts = entry.split(":")
		mode = "rw"
		if len(parts) > 1 and parts[-1] in ("ro", "rw"):
			mode = parts.pop()
		if len(parts) > 2:
			fail(f"Invalid {EXTRA_VOLUMES_VAR} entry '{entry}'. Expected host_path[:container_path][:ro|rw].")

		host = Path(parts[0]).expanduser()
		if not host.is_absolute():
			fail(f"{EXTRA_VOLUMES_VAR}: host path must be absolute or start with ~ ('{parts[0]}').")
		host = host.resolve()
		# Docker would create a missing host path as root, which causes the permission problems we avoid.
		if not host.exists():
			fail(f"{EXTRA_VOLUMES_VAR}: host path does not exist: {host}")

		if len(parts) == 2:
			target = parts[1]
		elif host.name:
			target = f"{WORKSPACE_ROOT}/{host.name}"
		else:
			fail(f"{EXTRA_VOLUMES_VAR}: '{entry}' needs an explicit container path.")
		if not target.startswith("/"):
			fail(f"{EXTRA_VOLUMES_VAR}: container path must be absolute ('{target}').")

		target = posixpath.normpath(target)
		if target == container_home or target in used_targets:
			fail(f"{EXTRA_VOLUMES_VAR}: container path {target} is already used. Give '{host}' an explicit container path.")
		used_targets.add(target)
		mounts.append(Mount(host, target, mode))

	return mounts


def write_compose_override(service_name: str, mounts: list[Mount]) -> bool:
	"""Generate docker-compose.override.yml for extra volumes. Returns True if it changed."""
	existing = OVERRIDE_FILE.read_text(encoding="utf-8") if OVERRIDE_FILE.exists() else None
	if existing is not None and not existing.startswith(OVERRIDE_MARKER):
		fail(f"{OVERRIDE_FILE.name} exists and was not generated by run.py. Move it away or merge it by hand.")

	if not mounts:
		if existing is None:
			return False
		OVERRIDE_FILE.unlink()
		return True

	lines = [
		f"{OVERRIDE_MARKER} from {EXTRA_VOLUMES_VAR} in .env. Do not edit.",
		"services:",
		f"  {service_name}:",
		"    volumes:",
	]
	for mount in mounts:
		# JSON strings are valid YAML scalars; '$' must be escaped for compose interpolation.
		spec = f"{mount.host}:{mount.target}:{mount.mode}".replace("$", "$$")
		lines.append(f"      - {json.dumps(spec)}")
	content = "\n".join(lines) + "\n"

	if content == existing:
		return False
	OVERRIDE_FILE.write_text(content, encoding="utf-8")
	return True


def sync_extra_volumes() -> bool:
	env_data = _load_dotenv()
	mounts = parse_extra_volumes(env_data, _get_container_home(env_data))
	return write_compose_override(get_service_name(), mounts)


def resolve_host_identity(env_data: dict[str, str]) -> tuple[str, str]:
	"""UID/GID the container user must have to match file ownership on the host."""
	uid = _get_setting("LOCAL_UID", env_data) or str(os.getuid())
	gid = _get_setting("LOCAL_GID", env_data)
	if not gid:
		home_mount = _parse_compose_mounts().get("Claude home mount")
		gid = str(home_mount.stat().st_gid) if home_mount is not None else str(os.getgid())

	if not (uid.isdigit() and gid.isdigit()):
		fail(f"LOCAL_UID/LOCAL_GID must be numeric (got uid={uid!r}, gid={gid!r}).")
	if uid == "0":
		fail("Refusing to run the container user as UID 0. Run as a regular user or set LOCAL_UID in .env.")
	return uid, gid


def image_needs_rebuild(uid: str, gid: str) -> bool:
	"""True when the image is missing or was built for a different UID/GID."""
	images = run(["docker", "compose", "config", "--images"], check=False, capture=True)
	names = images.stdout.split() if images.returncode == 0 else []
	if not names:
		return True

	labels = run(
		[
			"docker",
			"image",
			"inspect",
			"-f",
			'{{index .Config.Labels "claude.uid"}}:{{index .Config.Labels "claude.gid"}}',
			names[0],
		],
		check=False,
		capture=True,
	)
	return labels.returncode != 0 or labels.stdout.strip() != f"{uid}:{gid}"


def warn_if_home_not_owned(uid: str, gid: str) -> None:
	"""Warn when files in the home mount belong to a different UID than the container user."""
	home = _parse_compose_mounts().get("Claude home mount")
	if home is None:
		return

	foreign = [
		entry.name
		for entry in os.scandir(home)
		if entry.stat(follow_symlinks=False).st_uid != int(uid)
	]
	if foreign:
		examples = ", ".join(foreign[:3])
		print(
			f"⚠️  {len(foreign)} entries in {home} are not owned by UID {uid} (e.g. {examples}); "
			"Claude may be unable to read or write them.\n"
			f"   Fix with: sudo chown -R {uid}:{gid} {home}"
		)


def ensure_container_running(*, mounts_changed: bool, recreate: bool) -> None:
	uid, gid = resolve_host_identity(_load_dotenv())
	warn_if_home_not_owned(uid, gid)
	rebuild = image_needs_rebuild(uid, gid)

	if is_container_running() and not recreate:
		if mounts_changed or rebuild:
			print(
				"⚠️  The running container uses an outdated configuration (volumes or UID/GID changed). "
				"Run again with --recreate to apply it."
			)
		return

	service_name = get_service_name()
	print("🔍 Starting secure environment...")
	if rebuild:
		print(f"🔧 Building image for UID {uid} / GID {gid}...")

	# Compose build args read these; exporting them keeps image and host identity in sync.
	env = os.environ.copy()
	env["LOCAL_UID"] = uid
	env["LOCAL_GID"] = gid

	up_cmd = ["docker", "compose", "up", "-d"]
	if rebuild:
		up_cmd.append("--build")
	if recreate:
		up_cmd.append("--force-recreate")
	up_cmd.append(service_name)

	start = subprocess.run(up_cmd, cwd=PROJECT_DIR, env=env, check=False, text=True)
	if start.returncode != 0:
		fail("Failed to start container with docker compose up -d.")

	if not is_container_running():
		fail("Container did not reach running state after startup.")

	print("✅ Environment ready. Starting Claude Code session...")


def inspect_container() -> ContainerInfo | None:
	"""Read the user and bind mounts of the running container; None if unavailable."""
	container_ref = _container_ref()
	if container_ref is None:
		return None

	identity = run(
		["docker", "exec", container_ref, "sh", "-c", 'echo "$(id -un) $(id -u) $(id -g) $HOME"'],
		check=False,
		capture=True,
	)
	mounts_raw = run(["docker", "inspect", "-f", "{{json .Mounts}}", container_ref], check=False, capture=True)
	fields = identity.stdout.split()
	if identity.returncode != 0 or mounts_raw.returncode != 0 or len(fields) != 4:
		return None

	username, uid, gid, home = fields
	mounts = [
		Mount(Path(item["Source"]), item["Destination"], "rw" if item.get("RW") else "ro")
		for item in json.loads(mounts_raw.stdout)
		if item.get("Type") == "bind" and item["Destination"] != home
	]
	return ContainerInfo(username, uid, gid, home, mounts)


def build_environment_context(info: ContainerInfo) -> str:
	"""Describe the isolated environment so Claude knows where it runs and what it can reach."""
	if info.mounts:
		mount_lines = "\n".join(
			f"- {mount.target} ({'read-only' if mount.mode == 'ro' else 'read-write'}), "
			f"host directory '{mount.host.name}'"
			for mount in info.mounts
		)
	else:
		mount_lines = "- (none)"

	return (
		"# Execution environment\n\n"
		"You are running inside an isolated Docker container (Ubuntu), not directly on the user's computer.\n\n"
		f"- User: {info.username} (uid={info.uid}, gid={info.gid}). HOME is {info.home}.\n"
		f"- {info.home} is shared with the host, so its contents persist across sessions.\n"
		"- Files outside the shared locations exist only in the container and may be lost when it is recreated.\n"
		"- The rest of the host filesystem is not accessible.\n"
		"- Network: outbound internet access only; the container publishes no ports.\n\n"
		"Additional host directories mounted into the container:\n"
		f"{mount_lines}\n\n"
		"Do not write to read-only mounts. Keep project work inside the mounted directories so it is visible on the host."
	)


def build_claude_args() -> list[str]:
	info = inspect_container()
	if info is None:
		print("⚠️  Could not inspect the container; starting Claude without environment context.")
		return []

	args = ["--append-system-prompt", build_environment_context(info)]
	if info.mounts:
		# Grant access to the mounted directories, which live outside Claude's working directory.
		args += ["--add-dir", *(mount.target for mount in info.mounts)]
	return args


def launch_interactive_session(*, root_mode: bool = False) -> None:
	service_name = get_service_name()
	# Replace the Python process with docker compose exec for a clean terminal handoff.
	if root_mode:
		exec_cmd = [
			"docker",
			"compose",
			"exec",
			"--user",
			"root",
			service_name,
			"bash",
		]
	else:
		exec_cmd = [
			"docker",
			"compose",
			"exec",
			service_name,
			"claude",
			*build_claude_args(),
		]
	os.chdir(PROJECT_DIR)
	try:
		os.execvp(exec_cmd[0], exec_cmd)
	except OSError as error:
		fail(f"Could not open Claude Code session: {error}")


def main() -> None:
	args = parse_args()
	ensure_runtime_prereqs()
	if ensure_env_file_exists():
		# Compose needs .env, and its defaults (CLAUDE_DIR, UID/GID) may not match this machine.
		print(f"📝 Created {ENV_FILE} from {ENV_EXAMPLE_FILE.name}. Review it (CLAUDE_DIR, EXTRA_VOLUMES, LOCAL_UID) and run again.")
		sys.exit(0)
	preflight_checks()
	mounts_changed = sync_extra_volumes()
	ensure_container_running(mounts_changed=mounts_changed, recreate=args.recreate)
	launch_interactive_session(root_mode=args.root)

if __name__ == "__main__":
	main()
